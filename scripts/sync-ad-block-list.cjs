#!/usr/bin/env node
/**
 * Copies electron/ad-block-list.json (single source of truth) into the Android
 * GeckoView bridge extension as ad-block-list.json (read by BrowserAdBlock.java)
 * and ad-block-list.js (loaded by the extension background page).
 * Also copies electron/live-rewind-guard.js into the extension as
 * live-rewind-guard.js (source string injected into page world by content.js).
 */
const fs = require('fs')
const path = require('path')

const root = path.resolve(__dirname, '..')
const src = path.join(root, 'electron', 'ad-block-list.json')
const list = JSON.parse(fs.readFileSync(src, 'utf8'))
const outDir = path.join(root, 'android', 'app', 'src', 'main', 'assets', 'jiyu-gecko-bridge')
if (!fs.existsSync(outDir)) {
  console.log('[sync-ad-block-list] no android extension dir, skipped')
  process.exit(0)
}
const body = JSON.stringify({ version: list.version, hosts: list.hosts, urlPatterns: list.urlPatterns }, null, 2)
const header = '// GENERATED by scripts/sync-ad-block-list.cjs from electron/ad-block-list.json - do not edit.\n'
const writeIfChanged = (file, text) => {
  const prev = fs.existsSync(file) ? fs.readFileSync(file, 'utf8') : ''
  if (prev !== text) fs.writeFileSync(file, text)
}
writeIfChanged(path.join(outDir, 'ad-block-list.json'), body + '\n')
writeIfChanged(path.join(outDir, 'ad-block-list.js'), header + 'self.JIYU_AD_BLOCK = ' + body + '\n')
const guardSrc = fs.readFileSync(path.join(root, 'electron', 'live-rewind-guard.js'), 'utf8').replace(/\r\n/g, '\n')
writeIfChanged(
  path.join(outDir, 'live-rewind-guard.js'),
  '// GENERATED by scripts/sync-ad-block-list.cjs from electron/live-rewind-guard.js - do not edit.\n' +
    'var JIYU_LIVE_REWIND_GUARD_SRC = ' +
    JSON.stringify(guardSrc) +
    ';\n',
)
console.log('[sync-ad-block-list] ' + list.hosts.length + ' hosts, ' + list.urlPatterns.length + ' patterns')
