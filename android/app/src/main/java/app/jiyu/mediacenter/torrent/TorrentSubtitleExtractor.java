package app.jiyu.mediacenter.torrent;

import android.content.Context;
import android.util.Log;

import com.arthenica.ffmpegkit.FFmpegKit;
import com.arthenica.ffmpegkit.FFmpegKitConfig;
import com.arthenica.ffmpegkit.FFmpegSession;
import com.arthenica.ffmpegkit.ReturnCode;

import java.io.File;
import java.io.FileInputStream;
import java.nio.charset.StandardCharsets;
import java.util.ArrayList;
import java.util.List;
import java.util.Locale;
import java.util.concurrent.atomic.AtomicLong;
import java.util.regex.Matcher;
import java.util.regex.Pattern;

/**
 * Pull English softsubs out of MULTI anime packs (ASS/SRT inside the MKV).
 * Remux strips subtitle tracks, so the player needs a separate VTT URL.
 */
final class TorrentSubtitleExtractor {
  private static final String TAG = "JiyuTorrentSubs";
  private static final Pattern SUB_STREAM = Pattern.compile(
    "Stream\\s+#\\d+:(\\d+)(?:\\(([^)]*)\\))?:\\s*Subtitle:\\s*(\\S+)",
    Pattern.CASE_INSENSITIVE
  );
  private static final Pattern TITLE_LINE = Pattern.compile(
    "^\\s*title\\s*:\\s*(.+)$",
    Pattern.CASE_INSENSITIVE
  );

  private TorrentSubtitleExtractor() {}

  /** Outcome of one probe + extract pass. */
  enum Result {
    /** VTT complete with cues. */
    OK,
    /** Probe read the container header and it has no subtitle streams. */
    NO_TRACKS,
    /** Only image / Signs & Songs / forced tracks: nothing usable for dialogue. */
    NO_USABLE,
    /** Read error / truncated stream / ffmpeg failure: worth retrying later. */
    ERROR,
    /** Stopped on purpose (jump to the playhead / torrent removed); partial VTT kept. */
    CANCELLED
  }

  /** Signs / Songs / Forced-only tracks (e.g. "English Signs [Generated by Yameii]"). */
  static boolean isSignsOrForcedOnlyTitle(String rawTitle) {
    String title = rawTitle == null ? "" : rawTitle.toLowerCase(Locale.US);
    if (title.isEmpty()) return false;
    if (title.matches(".*\\b(full|dialogue|dialog|complete)\\b.*")) return false;
    return title.matches(".*\\b(signs?|songs?|forced|karaoke|op\\s*/\\s*ed)\\b.*");
  }

  private static boolean logsShowReadFailure(String logs) {
    if (logs == null) return false;
    String l = logs.toLowerCase(Locale.US);
    return l.contains("stream ends prematurely")
      || l.contains("read error")
      || l.contains("connection reset")
      || l.contains("error reading header")
      || l.contains("invalid data found when processing input");
  }

  private static final class Probe {
    final List<SubTrack> tracks;
    /** ffmpeg parsed the container header ("Input #0 ..."). */
    final boolean opened;
    final boolean readFailure;

    Probe(List<SubTrack> tracks, boolean opened, boolean readFailure) {
      this.tracks = tracks;
      this.opened = opened;
      this.readFailure = readFailure;
    }
  }

  /** ffmpeg http input options: resume on a dropped local stream instead of ending the file. */
  private static final String HTTP_INPUT_OPTS =
    "-reconnect 1 -reconnect_streamed 1 -reconnect_delay_max 30 ";

  static final class SubTrack {
    final int streamIndex;
    final int subtitleOrdinal;
    final String language;
    final String codec;
    final String title;
    final boolean isDefault;

    SubTrack(
      int streamIndex,
      int subtitleOrdinal,
      String language,
      String codec,
      String title,
      boolean isDefault
    ) {
      this.streamIndex = streamIndex;
      this.subtitleOrdinal = subtitleOrdinal;
      this.language = language != null ? language : "";
      this.codec = codec != null ? codec : "";
      this.title = title != null ? title : "";
      this.isDefault = isDefault;
    }
  }

  /** Convert a companion .srt/.ass/.vtt next to the video into {@code outVtt}. */
  static boolean convertCompanionFile(File companion, File outVtt) {
    if (companion == null || !companion.isFile() || companion.length() < 8 || outVtt == null) {
      return false;
    }
    try {
      String name = companion.getName().toLowerCase(Locale.US);
      if (name.endsWith(".vtt")) {
        return copyFile(companion, outVtt);
      }
      File parent = outVtt.getParentFile();
      if (parent != null && !parent.isDirectory() && !parent.mkdirs()) return false;
      if (outVtt.exists()) {
        //noinspection ResultOfMethodCallIgnored
        outVtt.delete();
      }
      String cmd =
        "-y -hide_banner -loglevel error -nostdin "
          + "-i " + quote(companion.getAbsolutePath()) + " "
          + "-f webvtt " + quote(outVtt.getAbsolutePath());
      FFmpegSession session = FFmpegKit.execute(cmd);
      if (!ReturnCode.isSuccess(session.getReturnCode())) {
        Log.w(TAG, "companion convert failed: " + session.getOutput());
        return false;
      }
      return outVtt.isFile() && outVtt.length() > 16;
    } catch (Throwable t) {
      Log.w(TAG, "companion convert failed", t);
      return false;
    }
  }

  static File findCompanionSubtitle(File videoFile) {
    if (videoFile == null) return null;
    File dir = videoFile.getParentFile();
    if (dir == null || !dir.isDirectory()) return null;
    String stem = videoFile.getName().replaceFirst("\\.[^.]+$", "").toLowerCase(Locale.US);
    File best = null;
    long bestScore = -1;
    File[] files = dir.listFiles();
    if (files == null) return null;
    for (File f : files) {
      if (!f.isFile()) continue;
      String n = f.getName().toLowerCase(Locale.US);
      if (!(n.endsWith(".srt") || n.endsWith(".ass") || n.endsWith(".ssa") || n.endsWith(".vtt"))) {
        continue;
      }
      // Signs/Songs/Forced-only companions carry no dialogue.
      String nameTitle = n.replaceFirst("\\.[^.]+$", "").replace('.', ' ').replace('_', ' ');
      if (isSignsOrForcedOnlyTitle(nameTitle)) continue;
      long score = 0;
      if (n.startsWith(stem)) score += 100;
      if (n.contains("eng") || n.contains(".en.") || n.endsWith(".en.srt") || n.endsWith(".en.ass")) {
        score += 50;
      }
      if (n.contains("signs") || n.contains("forced")) score -= 40;
      score += Math.min(20, f.length() / 50_000);
      if (score > bestScore) {
        bestScore = score;
        best = f;
      }
    }
    return best;
  }

  /**
   * Probe + extract best English dialogue softsub to {@code outVtt}.
   * The VTT is flushed per cue so the HTTP server can serve it while ffmpeg
   * is still reading the torrent (progressive subtitles).
   */
  static Result extractBestEnglish(Context context, String rawUrl, File outVtt) {
    return extractBestEnglish(context, rawUrl, outVtt, 0, null);
  }

  /**
   * @param startAt title position (s) to start reading at; cue times stay on the title
   *     clock (-copyts) so runs started at different points merge cleanly.
   * @param sessionId receives the running ffmpeg session id (0 when none) so another
   *     thread can cancel it with {@link FFmpegKit#cancel(long)}.
   */
  static Result extractBestEnglish(
    Context context,
    String rawUrl,
    File outVtt,
    double startAt,
    AtomicLong sessionId
  ) {
    if (rawUrl == null || rawUrl.isEmpty() || outVtt == null) return Result.ERROR;
    try {
      Probe probe = probeSubtitleTracks(rawUrl);
      if (probe.tracks.isEmpty()) {
        if (probe.opened && !probe.readFailure) {
          Log.i(TAG, "no subtitle tracks in " + rawUrl);
          return Result.NO_TRACKS;
        }
        Log.w(TAG, "subtitle probe could not read " + rawUrl + " (will retry)");
        return Result.ERROR;
      }
      SubTrack best = pickBestTextTrack(probe.tracks);
      if (best == null) {
        Log.i(TAG, "no usable dialogue softsub track (image / signs / forced only)");
        return Result.NO_USABLE;
      }
      Log.i(
        TAG,
        "extracting s:" + best.subtitleOrdinal
          + " stream=" + best.streamIndex
          + " lang=" + best.language
          + " codec=" + best.codec
          + " title=" + best.title
      );

      File parent = outVtt.getParentFile();
      if (parent != null && !parent.isDirectory() && !parent.mkdirs()) {
        return Result.ERROR;
      }
      if (outVtt.exists()) {
        //noinspection ResultOfMethodCallIgnored
        outVtt.delete();
      }

      String seek = startAt >= 1
        ? String.format(Locale.US, "-ss %.3f -copyts ", startAt)
        : "";
      String cmd =
        "-y -hide_banner -loglevel error -nostdin "
          + HTTP_INPUT_OPTS
          + "-probesize 32M -analyzeduration 20000000 "
          + seek
          + "-i " + quote(rawUrl) + " "
          + "-map 0:" + best.streamIndex + " "
          + "-flush_packets 1 "
          + "-f webvtt " + quote(outVtt.getAbsolutePath());

      FFmpegSession session = FFmpegSession.create(FFmpegKitConfig.parseArguments(cmd));
      if (sessionId != null) sessionId.set(session.getSessionId());
      try {
        FFmpegKitConfig.ffmpegExecute(session);
      } finally {
        if (sessionId != null) sessionId.set(0);
      }
      String logs = session.getAllLogsAsString();
      if (logs == null || logs.isEmpty()) logs = session.getOutput();
      if (ReturnCode.isCancel(session.getReturnCode())) {
        Log.i(TAG, "extract cancelled at start=" + startAt);
        return Result.CANCELLED;
      }
      if (!ReturnCode.isSuccess(session.getReturnCode())) {
        Log.w(TAG, "extract failed: " + logs);
        return Result.ERROR;
      }
      // ffmpeg treats an http read error as EOF and exits 0 with a truncated VTT.
      if (logsShowReadFailure(logs)) {
        Log.w(TAG, "extract hit a read error (will retry): " + logs);
        return Result.ERROR;
      }
      if (!outVtt.isFile() || outVtt.length() < 16) {
        Log.w(TAG, "extract produced empty VTT");
        return Result.NO_USABLE;
      }
      Log.i(TAG, "softsubs ready " + outVtt.length() + " bytes");
      return Result.OK;
    } catch (Throwable t) {
      Log.w(TAG, "extract failed", t);
      return Result.ERROR;
    }
  }
  /** Complete cue blocks of a (possibly still growing) VTT, without the WEBVTT header. */
  static String completeCueBody(File vtt) {
    try {
      if (vtt == null || !vtt.isFile()) return "";
      long len = vtt.length();
      if (len <= 16 || len > 32L * 1024L * 1024L) return "";
      byte[] buf = new byte[(int) len];
      int read = 0;
      try (FileInputStream in = new FileInputStream(vtt)) {
        while (read < buf.length) {
          int n = in.read(buf, read, buf.length - read);
          if (n < 0) break;
          read += n;
        }
      }
      String text = new String(buf, 0, read, StandardCharsets.UTF_8).replace("\r\n", "\n");
      int cut = text.lastIndexOf("\n\n");
      if (cut <= 0) return "";
      return stripVttHeader(text.substring(0, cut + 2));
    } catch (Throwable t) {
      return "";
    }
  }

  /** Drop the leading "WEBVTT" header block, keeping only cue blocks. */
  static String stripVttHeader(String vtt) {
    if (vtt == null) return "";
    String text = vtt.replace("\r\n", "\n");
    if (text.startsWith("\uFEFF")) text = text.substring(1);
    if (!text.startsWith("WEBVTT")) return text;
    int blank = text.indexOf("\n\n");
    return blank < 0 ? "" : text.substring(blank + 2);
  }

  private static final Pattern CUE_TIMING = Pattern.compile(
    "(?:(\\d+):)?(\\d{1,2}):(\\d{2})[.,](\\d{1,3})\\s*-->\\s*(?:(\\d+):)?(\\d{1,2}):(\\d{2})[.,](\\d{1,3})"
  );

  /** Latest cue end (s) in VTT text, or 0. */
  static double lastCueEndSeconds(String vtt) {
    if (vtt == null || vtt.isEmpty()) return 0;
    double max = 0;
    Matcher m = CUE_TIMING.matcher(vtt);
    while (m.find()) {
      double h = m.group(5) != null ? Double.parseDouble(m.group(5)) : 0;
      double end = h * 3600
        + Double.parseDouble(m.group(6)) * 60
        + Double.parseDouble(m.group(7))
        + Double.parseDouble("0." + m.group(8));
      if (end > max) max = end;
    }
    return max;
  }

  private static Probe probeSubtitleTracks(String rawUrl) {
    List<SubTrack> tracks = new ArrayList<>();
    boolean opened = false;
    boolean readFailure = false;
    try {
      String probeCmd =
        "-hide_banner " + HTTP_INPUT_OPTS
          + "-probesize 32M -analyzeduration 20000000 -i " + quote(rawUrl);
      FFmpegSession session = FFmpegKit.execute(probeCmd);
      String logs = session.getAllLogsAsString();
      if (logs == null || logs.isEmpty()) logs = session.getOutput();
      if (logs == null) return new Probe(tracks, false, true);
      opened = logs.contains("Input #0");
      readFailure = logsShowReadFailure(logs);

      SubTrack current = null;
      int subtitleOrdinal = -1;
      for (String line : logs.split("\\r?\\n")) {
        Matcher stream = SUB_STREAM.matcher(line);
        if (stream.find()) {
          if (current != null) tracks.add(current);
          subtitleOrdinal += 1;
          int streamIndex = Integer.parseInt(stream.group(1));
          String lang = stream.group(2) != null ? stream.group(2).trim().toLowerCase(Locale.US) : "";
          String codec = stream.group(3) != null ? stream.group(3).trim().toLowerCase(Locale.US) : "";
          boolean isDefault = line.toLowerCase(Locale.US).contains("(default)");
          current = new SubTrack(streamIndex, subtitleOrdinal, lang, codec, "", isDefault);
          continue;
        }
        if (current != null) {
          Matcher title = TITLE_LINE.matcher(line);
          if (title.find()) {
            current = new SubTrack(
              current.streamIndex,
              current.subtitleOrdinal,
              current.language,
              current.codec,
              title.group(1).trim(),
              current.isDefault
            );
          }
        }
      }
      if (current != null) tracks.add(current);
    } catch (Throwable t) {
      Log.w(TAG, "subtitle probe failed", t);
      readFailure = true;
    }
    return new Probe(tracks, opened, readFailure);
  }

  private static SubTrack pickBestTextTrack(List<SubTrack> tracks) {
    SubTrack best = null;
    double bestScore = Double.NEGATIVE_INFINITY;
    for (SubTrack track : tracks) {
      double score = scoreSubtitleTrack(track);
      if (score > bestScore) {
        bestScore = score;
        best = track;
      }
    }
    return bestScore > 0 ? best : null;
  }

  private static double scoreSubtitleTrack(SubTrack track) {
    double score = 0;
    String lang = track.language;
    String title = track.title.toLowerCase(Locale.US);
    String codec = track.codec;

    // Signs & Songs / Forced-only tracks are not dialogue: never pick them, so the
    // caller reports "no subtitle track" and the next release gets tried.
    if (isSignsOrForcedOnlyTitle(track.title)) return Double.NEGATIVE_INFINITY;

    if (isTextSubtitleCodec(codec)) score += 100;
    else if (isImageSubtitleCodec(codec)) score -= 200;
    else score += 10;

    if (lang.matches("^(eng?|en)$") || lang.startsWith("en")) score += 50;
    else if (lang.isEmpty() || lang.equals("und") || lang.equals("unknown")) score += 5;
    else if (lang.matches("^(jpn?|ja|chi|zho|kor|ko|spa|es|fre?|fr).*")) score -= 15;

    if (title.matches(".*\\b(full|dialogue|dialog|english)\\b.*")) score += 25;
    if (title.matches(".*\\b(signs?|songs?|forced|commentary)\\b.*")) score -= 40;
    if (title.matches(".*\\b(sdh|hearing\\s*impaired|cc)\\b.*")) score -= 20;
    if (track.isDefault) score += 8;
    score -= track.subtitleOrdinal * 0.1;
    return score;
  }

  private static boolean isTextSubtitleCodec(String codec) {
    String c = codec.toLowerCase(Locale.US);
    return c.contains("ass") || c.contains("ssa") || c.contains("subrip")
      || c.contains("srt") || c.contains("webvtt") || c.contains("mov_text")
      || c.contains("text");
  }

  private static boolean isImageSubtitleCodec(String codec) {
    String c = codec.toLowerCase(Locale.US);
    return c.contains("hdmv") || c.contains("pgs") || c.contains("dvd_subtitle")
      || c.contains("dvb_subtitle") || c.contains("xsub");
  }

  private static boolean copyFile(File from, File to) throws java.io.IOException {
    File parent = to.getParentFile();
    if (parent != null && !parent.isDirectory() && !parent.mkdirs()) return false;
    try (
      java.io.InputStream in = new java.io.FileInputStream(from);
      java.io.OutputStream out = new java.io.FileOutputStream(to)
    ) {
      byte[] buf = new byte[8192];
      int n;
      while ((n = in.read(buf)) >= 0) {
        if (n > 0) out.write(buf, 0, n);
      }
    }
    return to.isFile() && to.length() > 16;
  }

  private static String quote(String value) {
    return "\"" + value.replace("\"", "") + "\"";
  }
}
